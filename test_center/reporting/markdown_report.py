"""Markdown report generator for the Test & Evaluation Center.

Produces thesis-ready Markdown reports with tables, checksums,
and methodology notes.
"""
from __future__ import annotations

import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


def _fmt(value: Any, decimals: int = 6) -> str:
    """Format a numeric value for Markdown display."""
    if value is None:
        return "—"
    try:
        return f"{float(value):.{decimals}f}"
    except (TypeError, ValueError):
        return str(value)


def generate_markdown_report(report_data: dict[str, Any], output_path: Path) -> Path:
    """Generate a structured Markdown report.

    Args:
        report_data: Report dict from a TEC run.
        output_path: Destination for the ``.md`` file.

    Returns:
        The resolved ``output_path`` that was written.
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    _w = lines.append

    meta = report_data.get("metadata", {})
    overall = report_data.get("overall_status", "UNKNOWN")

    # Header
    _w("# MovSug — Test & Evaluation Report")
    _w("")
    _w(f"**Run ID:** `{meta.get('run_id', '—')}`  ")
    _w(f"**Timestamp:** {meta.get('timestamp_utc', '—')}  ")
    _w(f"**Git Commit:** `{meta.get('git_commit', '—')}`  ")
    _w(f"**Platform:** {meta.get('platform_info', '—')}  ")
    _w(f"**Overall Status:** **{overall}**")
    _w("")

    # Summary table
    summary = report_data.get("summary", {})
    _render_summary(lines, summary)

    # Functional tests
    _render_functional_tests(lines, report_data.get("functional_tests", []))

    # Coverage
    _render_coverage(lines, report_data.get("coverage", {}))

    # Lint / build checks
    _render_lint(lines, report_data.get("lint", {}))
    _render_build(lines, report_data.get("build_check", {}))

    # Recommendation metrics
    _render_rec_metrics(lines, report_data.get("recommendation_metrics", {}))

    # Phase 8A Metadata Enrichment
    _render_metadata_enrichment(lines, report_data.get("metadata_enrichment", {}))

    # MMR trade-off
    _render_mmr(lines, report_data.get("mmr_tradeoff", {}))

    # Latency comparison
    _render_latency(lines, report_data.get("latency_comparison", []))

    # Security
    _render_security(lines, report_data.get("security_findings", []))

    # Known limitations
    _render_limitations(lines, report_data.get("known_limitations", []))

    # Methodology
    _render_methodology(lines, report_data)

    # Footer
    _w("---")
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    _w(f"*Generated by MovSug Test & Evaluation Center — {now}*")
    _w("")

    content = "\n".join(lines)
    output_path.write_text(content, encoding="utf-8")
    logger.info("Markdown report written to %s", output_path)
    return output_path


def generate_vietnamese_summary(
    report_data: dict[str, Any], output_path: Path,
) -> Path:
    """Generate a Vietnamese executive summary (bao_cao_tom_tat.md).

    Technical terms (TF-IDF, NDCG, Precision, Coverage, etc.) are kept in
    English per academic convention.  The structure and narrative are in
    Vietnamese.

    Args:
        report_data: Report dict from a TEC run.
        output_path: Destination for the ``.md`` file.

    Returns:
        The resolved ``output_path`` that was written.
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    _w = lines.append

    meta = report_data.get("metadata", {})
    overall = report_data.get("overall_status", "UNKNOWN")
    summary = report_data.get("summary", {})
    func = summary.get("functional", {})
    rec = report_data.get("recommendation_metrics", {})

    _w("# MovSug — Báo Cáo Tóm Tắt Kiểm Thử và Đánh Giá")
    _w("")
    _w(f"**Mã chạy (Run ID):** `{meta.get('run_id', '—')}`  ")
    _w(f"**Thời gian:** {meta.get('timestamp_utc', '—')}  ")
    _w(f"**Git Commit:** `{meta.get('git_commit', '—')}`  ")
    _w(f"**Kết quả tổng thể:** **{overall}**")
    _w("")

    # Tổng quan kiểm thử
    _w("## 1. Tổng Quan Kiểm Thử Chức Năng")
    _w("")
    total = func.get("total", 0)
    passed = func.get("passed", 0)
    failed = func.get("failed", 0)
    _w(f"- **Tổng số test:** {total}")
    _w(f"- **Đạt (Passed):** {passed}")
    _w(f"- **Thất bại (Failed):** {failed}")
    _w(f"- **Tỷ lệ đạt:** {passed/total*100:.1f}%" if total > 0 else "- **Tỷ lệ đạt:** N/A")
    _w("")

    be = summary.get("backend_tests", {})
    fe = summary.get("frontend_tests", {})
    _w("| Thành phần | Tổng | Đạt | Thất bại | Bỏ qua | Trạng thái |")
    _w("|------------|-----:|----:|---------:|-------:|------------|")
    _w(f"| Backend | {be.get('total', '—')} | {be.get('passed', '—')} "
       f"| {be.get('failed', '—')} | {be.get('skipped', '—')} | {be.get('status', '—')} |")
    _w(f"| Frontend | {fe.get('total', '—')} | {fe.get('passed', '—')} "
       f"| {fe.get('failed', '—')} | {fe.get('skipped', '—')} | {fe.get('status', '—')} |")
    _w("")

    # Coverage
    coverage = report_data.get("coverage", {})
    if coverage:
        _w("## 2. Mức Độ Bao Phủ Mã Nguồn (Code Coverage)")
        _w("")
        for comp in ("backend", "frontend"):
            cdata = coverage.get(comp, {})
            if cdata and "line_rate" in cdata:
                _w(f"- **{comp.title()}:** {cdata['line_rate']*100:.1f}% line coverage")
            else:
                note = cdata.get("note", cdata.get("error", "Không có dữ liệu"))
                _w(f"- **{comp.title()}:** {note}")
        _w("")

    # Recommendation metrics
    by_k = rec.get("by_k", {})
    if by_k:
        _w("## 3. Kết Quả Đánh Giá Hệ Thống Gợi Ý")
        _w("")
        _w("Thuật toán đánh giá: **TF-IDF v1.1** (có hỗ trợ MMR re-ranking)")
        _w("")

        first_k_data = next(iter(by_k.values()), {})
        metric_names = sorted(first_k_data.keys())
        header = "| K | " + " | ".join(metric_names) + " |"
        sep = "|---|" + "|".join(["---:" for _ in metric_names]) + "|"
        _w(header)
        _w(sep)
        for k_label in sorted(by_k.keys()):
            metrics = by_k[k_label]
            vals = " | ".join(_fmt(metrics.get(m), 6) for m in metric_names)
            _w(f"| {k_label} | {vals} |")
        _w("")

        ds = rec.get("dataset_checksum", "")
        sp = rec.get("split_checksum", "")
        if ds:
            _w(f"- **Dataset SHA-256:** `{ds}`")
        if sp:
            _w(f"- **Split SHA-256:** `{sp}`")
        _w("")

    # Lint / Build
    lint = report_data.get("lint", {})
    build = report_data.get("build_check", {})
    if lint or build:
        _w("## 4. Chất Lượng Mã Nguồn")
        _w("")
        if lint:
            _w(f"- **ESLint:** {lint.get('errors', 0)} lỗi, {lint.get('warnings', 0)} cảnh báo")
        if build:
            _w(f"- **TypeScript build:** {build.get('status', '—')} "
               f"({build.get('error_count', 0)} lỗi kiểu)")
        _w("")

    # Hạn chế
    limitations = report_data.get("known_limitations", [])
    if limitations:
        _w("## 5. Hạn Chế Đã Biết")
        _w("")
        for lim in limitations:
            _w(f"- {lim}")
        _w("")

    # Khả năng tái tạo
    _w("## 6. Khả Năng Tái Tạo (Reproducibility)")
    _w("")
    _w(f"- **Git Commit:** `{meta.get('git_commit', '—')}`")
    _w(f"- **Python:** `{meta.get('python_version', '—')}`")
    _w(f"- **Nền tảng:** {meta.get('platform_info', '—')}")
    _w("")

    _w("---")
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    _w(f"*Được tạo bởi MovSug Test & Evaluation Center — {now}*")
    _w("")

    content = "\n".join(lines)
    output_path.write_text(content, encoding="utf-8")
    logger.info("Vietnamese summary written to %s", output_path)
    return output_path


def _render_summary(lines: list[str], summary: dict[str, Any]) -> None:
    """Render the summary section."""
    lines.append("## Summary")
    lines.append("")

    func = summary.get("functional", {})
    backend = summary.get("backend_tests", {})
    frontend = summary.get("frontend_tests", {})
    rec = summary.get("recommendations", {})

    lines.append("| Category | Total | Passed | Failed | Skipped | Status |")
    lines.append("|----------|------:|-------:|-------:|--------:|--------|")
    lines.append(
        f"| Backend  | {backend.get('total', '—')} "
        f"| {backend.get('passed', '—')} "
        f"| {backend.get('failed', '—')} "
        f"| {backend.get('skipped', '—')} "
        f"| {backend.get('status', '—')} |"
    )
    lines.append(
        f"| Frontend | {frontend.get('total', '—')} "
        f"| {frontend.get('passed', '—')} "
        f"| {frontend.get('failed', '—')} "
        f"| {frontend.get('skipped', '—')} "
        f"| {frontend.get('status', '—')} |"
    )
    lines.append(
        f"| **Total** | **{func.get('total', '—')}** "
        f"| **{func.get('passed', '—')}** "
        f"| **{func.get('failed', '—')}** "
        f"| **{func.get('skipped', '—')}** "
        f"| **{func.get('status', '—')}** |"
    )
    lines.append(
        f"| Rec. Experiments | — | — | — | — "
        f"| {rec.get('status', '—')} |"
    )
    lines.append("")


def _render_functional_tests(lines: list[str], tests: list[dict]) -> None:
    """Render the functional test results section."""
    if not tests:
        return
    lines.append("## Functional Test Results")
    lines.append("")

    failures = [
        t for t in tests
        if t.get("status", "").upper() in ("FAIL", "FAILED", "ERROR")
    ]

    total = len(tests)
    passed = sum(1 for t in tests if t.get("status", "").upper() in ("PASS", "PASSED"))
    lines.append(f"**{passed}/{total}** tests passed.")
    lines.append("")

    if failures:
        lines.append("### Failures")
        lines.append("")
        for t in failures:
            name = t.get("name", "unknown")
            msg = t.get("message", t.get("failure_message", ""))
            lines.append(f"- **{name}**: {msg}")
        lines.append("")


def _render_rec_metrics(
    lines: list[str], rec: dict[str, Any]
) -> None:
    """Render recommendation metrics tables."""
    if not rec:
        return
    by_k = rec.get("by_k", {})
    if not by_k:
        return

    lines.append("## Recommendation Metrics")
    lines.append("")

    # Get metric names from first entry
    first_k = next(iter(by_k.values()), {})
    metric_names = sorted(first_k.keys())

    header = "| K | " + " | ".join(metric_names) + " |"
    sep = "|---|" + "|".join(["---:" for _ in metric_names]) + "|"
    lines.append(header)
    lines.append(sep)

    for k_label in sorted(by_k.keys()):
        metrics = by_k[k_label]
        vals = " | ".join(_fmt(metrics.get(m), 6) for m in metric_names)
        lines.append(f"| {k_label} | {vals} |")
    lines.append("")

    # Latency
    lat = rec.get("latency", {})
    if lat:
        lines.append("### Latency")
        lines.append("")
        lines.append("| Percentile | Value (ms) |")
        lines.append("|------------|----------:|")
        for k, v in lat.items():
            lines.append(f"| {k} | {_fmt(v, 2)} |")
        lines.append("")


def _render_mmr(lines: list[str], mmr: dict[str, Any]) -> None:
    """Render MMR trade-off section."""
    if not mmr:
        return
    variants = mmr.get("variants", {})
    if not variants:
        return

    lines.append("## MMR Relevance–Diversity Trade-off")
    lines.append("")
    lines.append("| Variant | NDCG@10 | ILD@10 | Coverage@10 | P50 Latency (ms) |")
    lines.append("|---------|--------:|-------:|------------:|------------------:|")

    for vid, vdata in variants.items():
        name = vdata.get("name", vid)
        metrics = vdata.get("metrics", {})
        k10 = metrics.get("by_k", {}).get("k_10", {})
        lat = metrics.get("latency", {})
        lines.append(
            f"| {name} "
            f"| {_fmt(k10.get('ndcg'))} "
            f"| {_fmt(k10.get('intra_list_diversity'), 4)} "
            f"| {_fmt(k10.get('catalog_coverage'), 4)} "
            f"| {_fmt(lat.get('p50_ms'), 2)} |"
        )
    lines.append("")


def _render_latency(lines: list[str], lat_data: list[dict]) -> None:
    """Render latency comparison section."""
    if not lat_data:
        return
    lines.append("## Latency Comparison")
    lines.append("")
    lines.append("| Experiment | P50 (ms) | P90 (ms) | P95 (ms) | Mean (ms) |")
    lines.append("|------------|----------:|----------:|----------:|----------:|")
    for entry in lat_data:
        lines.append(
            f"| {entry.get('name', '—')} "
            f"| {_fmt(entry.get('p50_ms'), 2)} "
            f"| {_fmt(entry.get('p90_ms'), 2)} "
            f"| {_fmt(entry.get('p95_ms'), 2)} "
            f"| {_fmt(entry.get('mean_ms'), 2)} |"
        )
    lines.append("")


def _render_security(lines: list[str], findings: list[dict]) -> None:
    """Render security findings section."""
    if not findings:
        return
    lines.append("## Security Findings")
    lines.append("")
    lines.append("| Severity | Title | Location |")
    lines.append("|----------|-------|----------|")
    for f in findings:
        lines.append(
            f"| {f.get('severity', '—')} "
            f"| {f.get('title', '—')} "
            f"| {f.get('location', '—')} |"
        )
    lines.append("")


def _render_coverage(lines: list[str], coverage: dict[str, Any]) -> None:
    """Render coverage section."""
    if not coverage:
        return
    lines.append("## Test Coverage")
    lines.append("")

    lines.append("| Component | Line Rate | Covered | Missing | Statements |")
    lines.append("|-----------|----------:|--------:|--------:|-----------:|")

    for component in ("backend", "frontend"):
        data = coverage.get(component, {})
        if not data or "error" in data:
            status = data.get("error", data.get("note", "N/A"))
            lines.append(f"| {component.title()} | — | — | — | {status} |")
        else:
            rate = data.get("line_rate", 0)
            covered = data.get("covered_lines", "—")
            missing = data.get("missing_lines", "—")
            stmts = data.get("num_statements", data.get("total_lines", "—"))
            lines.append(
                f"| {component.title()} | {rate*100:.1f}% "
                f"| {covered} | {missing} | {stmts} |"
            )
    lines.append("")


def _render_lint(lines: list[str], lint: dict[str, Any]) -> None:
    """Render ESLint results."""
    if not lint:
        return
    lines.append("## ESLint Analysis")
    lines.append("")
    status = lint.get("status", "—")
    errors = lint.get("errors", 0)
    warnings = lint.get("warnings", 0)
    files = lint.get("files_checked", 0)
    lines.append(f"- **Status:** {status}")
    lines.append(f"- **Errors:** {errors}")
    lines.append(f"- **Warnings:** {warnings}")
    lines.append(f"- **Files checked:** {files}")
    lines.append("")


def _render_build(lines: list[str], build: dict[str, Any]) -> None:
    """Render TypeScript build check results."""
    if not build:
        return
    lines.append("## TypeScript Build Check")
    lines.append("")
    status = build.get("status", "—")
    error_count = build.get("error_count", 0)
    lines.append(f"- **Status:** {status}")
    lines.append(f"- **Type errors:** {error_count}")
    if build.get("errors_sample"):
        lines.append("")
        lines.append("### Sample errors")
        lines.append("```")
        for err in build["errors_sample"][:10]:
            lines.append(err)
        lines.append("```")
    lines.append("")


def _render_metadata_enrichment(lines: list[str], enr: dict[str, Any]) -> None:
    """Render Phase 8A Movie Metadata Enrichment metrics."""
    if not enr or not enr.get("total_movies_inspected"):
        return

    before_overall = enr.get("completeness_before", {}).get("overall_completeness_ratio", 0.0)
    after_overall = enr.get("completeness_after", {}).get("overall_completeness_ratio", 0.0)
    lines.append("## Phase 8A — Movie Metadata Enrichment")
    lines.append("")
    lines.append(f"- **Evidence Type:** `{enr.get('evidence_type', 'mocked_controlled_verification')}`")
    lines.append(f"- **Total Movies Inspected:** {enr.get('total_movies_inspected', 0)}")
    lines.append(f"- **Movies with Missing Metadata:** {enr.get('movies_with_missing_metadata', 0)}")
    lines.append(f"- **Overall Completeness:** {before_overall * 100:.2f}% → **{after_overall * 100:.2f}%**")
    lines.append(f"- **Candidates Found:** {enr.get('candidates_found', 0)}")
    lines.append(f"- **Verified External ID Matches:** {enr.get('verified_id_matches', 0)}")
    lines.append(f"- **Ambiguous Matches:** {enr.get('ambiguous_matches', 0)}")
    lines.append(f"- **No-Match Cases:** {enr.get('no_match_cases', 0)}")
    lines.append(f"- **Admin Approval Rate:** {enr.get('admin_approval_rate', 0.0) * 100:.2f}%")
    lines.append(f"- **Admin Rejection Rate:** {enr.get('rejection_rate', 0.0) * 100:.2f}%")
    lines.append(f"- **API Failures / HTTP 429 / Retries:** {enr.get('api_failures', 0)} / {enr.get('http_429_responses', 0)} / {enr.get('retry_counts', 0)}")
    lines.append(
        f"- **Processing Time (p50 / p95):** "
        f"{enr.get('processing_time_p50_ms', 0.0):.2f} ms / {enr.get('processing_time_p95_ms', 0.0):.2f} ms"
    )
    lines.append(f"- **Duplicate or Conflicting Records:** {enr.get('duplicate_or_conflicting_records', 0)}")
    lines.append(f"- **Database Application Failures:** {enr.get('db_application_failures', 0)}")
    lines.append(f"- **Successful Recommendation Cache Refreshes:** {enr.get('successful_cache_refreshes', 0)}")
    lines.append("")

    before_fields = enr.get("completeness_before", {}).get("fields", {})
    after_fields = enr.get("completeness_after", {}).get("fields", {})
    if before_fields and after_fields:
        lines.append("### Field-Level Completeness (Before vs. After)")
        lines.append("")
        lines.append("| Field | Before (Populated) | Before (%) | After (Populated) | After (%) | Delta |")
        lines.append("|-------|-------------------:|-----------:|------------------:|----------:|------:|")
        for field, b_info in before_fields.items():
            a_info = after_fields.get(field, {})
            b_pop = b_info.get("populated", 0)
            b_pct = b_info.get("completeness_ratio", 0.0) * 100
            a_pop = a_info.get("populated", 0)
            a_pct = a_info.get("completeness_ratio", 0.0) * 100
            delta = a_pct - b_pct
            lines.append(
                f"| `{field}` | {b_pop} | {b_pct:.1f}% | {a_pop} | {a_pct:.1f}% | {delta:+.1f}% |"
            )
        lines.append("")


def _render_limitations(lines: list[str], limitations: list[str]) -> None:
    """Render known limitations section."""
    if not limitations:
        return
    lines.append("## Known Limitations")
    lines.append("")
    for lim in limitations:
        lines.append(f"- {lim}")
    lines.append("")


def _render_methodology(lines: list[str], data: dict[str, Any]) -> None:
    """Render methodology and reproducibility notes."""
    lines.append("## Reproducibility")
    lines.append("")

    meta = data.get("metadata", {})
    rec = data.get("recommendation_metrics", {})

    lines.append(f"- **Git Commit:** `{meta.get('git_commit', '—')}`")
    lines.append(f"- **Python Version:** `{meta.get('python_version', '—')}`")
    lines.append(f"- **Node Version:** `{meta.get('node_version', '—')}`")

    ds = rec.get("dataset_checksum", "")
    sp = rec.get("split_checksum", "")
    if ds:
        lines.append(f"- **Dataset SHA-256:** `{ds}`")
    if sp:
        lines.append(f"- **Split SHA-256:** `{sp}`")
    lines.append("")
