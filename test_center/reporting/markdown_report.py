"""Markdown report generator for the Test & Evaluation Center.

Produces thesis-ready Markdown reports with tables, checksums,
and methodology notes.
"""
from __future__ import annotations

import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


def _fmt(value: Any, decimals: int = 6) -> str:
    """Format a numeric value for Markdown display."""
    if value is None:
        return "—"
    try:
        return f"{float(value):.{decimals}f}"
    except (TypeError, ValueError):
        return str(value)


def generate_markdown_report(report_data: dict[str, Any], output_path: Path) -> Path:
    """Generate a structured Markdown report.

    Args:
        report_data: Report dict from a TEC run.
        output_path: Destination for the ``.md`` file.

    Returns:
        The resolved ``output_path`` that was written.
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    _w = lines.append

    meta = report_data.get("metadata", {})
    overall = report_data.get("overall_status", "UNKNOWN")

    # Header
    _w("# MovSug — Test & Evaluation Report")
    _w("")
    _w(f"**Run ID:** `{meta.get('run_id', '—')}`  ")
    _w(f"**Timestamp:** {meta.get('timestamp_utc', '—')}  ")
    _w(f"**Git Commit:** `{meta.get('git_commit', '—')}`  ")
    _w(f"**Platform:** {meta.get('platform_info', '—')}  ")
    _w(f"**Overall Status:** **{overall}**")
    _w("")

    # Summary table
    summary = report_data.get("summary", {})
    _render_summary(lines, summary)

    # Functional tests
    _render_functional_tests(lines, report_data.get("functional_tests", []))

    # Recommendation metrics
    _render_rec_metrics(lines, report_data.get("recommendation_metrics", {}))

    # MMR trade-off
    _render_mmr(lines, report_data.get("mmr_tradeoff", {}))

    # Latency comparison
    _render_latency(lines, report_data.get("latency_comparison", []))

    # Security
    _render_security(lines, report_data.get("security_findings", []))

    # Known limitations
    _render_limitations(lines, report_data.get("known_limitations", []))

    # Methodology
    _render_methodology(lines, report_data)

    # Footer
    _w("---")
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    _w(f"*Generated by MovSug Test & Evaluation Center — {now}*")
    _w("")

    content = "\n".join(lines)
    output_path.write_text(content, encoding="utf-8")
    logger.info("Markdown report written to %s", output_path)
    return output_path


def _render_summary(lines: list[str], summary: dict[str, Any]) -> None:
    """Render the summary section."""
    lines.append("## Summary")
    lines.append("")

    func = summary.get("functional", {})
    backend = summary.get("backend_tests", {})
    frontend = summary.get("frontend_tests", {})
    rec = summary.get("recommendations", {})

    lines.append("| Category | Total | Passed | Failed | Skipped | Status |")
    lines.append("|----------|------:|-------:|-------:|--------:|--------|")
    lines.append(
        f"| Backend  | {backend.get('total', '—')} "
        f"| {backend.get('passed', '—')} "
        f"| {backend.get('failed', '—')} "
        f"| {backend.get('skipped', '—')} "
        f"| {backend.get('status', '—')} |"
    )
    lines.append(
        f"| Frontend | {frontend.get('total', '—')} "
        f"| {frontend.get('passed', '—')} "
        f"| {frontend.get('failed', '—')} "
        f"| {frontend.get('skipped', '—')} "
        f"| {frontend.get('status', '—')} |"
    )
    lines.append(
        f"| **Total** | **{func.get('total', '—')}** "
        f"| **{func.get('passed', '—')}** "
        f"| **{func.get('failed', '—')}** "
        f"| **{func.get('skipped', '—')}** "
        f"| **{func.get('status', '—')}** |"
    )
    lines.append(
        f"| Rec. Experiments | — | — | — | — "
        f"| {rec.get('status', '—')} |"
    )
    lines.append("")


def _render_functional_tests(lines: list[str], tests: list[dict]) -> None:
    """Render the functional test results section."""
    if not tests:
        return
    lines.append("## Functional Test Results")
    lines.append("")

    failures = [
        t for t in tests
        if t.get("status", "").upper() in ("FAIL", "FAILED", "ERROR")
    ]

    total = len(tests)
    passed = sum(1 for t in tests if t.get("status", "").upper() in ("PASS", "PASSED"))
    lines.append(f"**{passed}/{total}** tests passed.")
    lines.append("")

    if failures:
        lines.append("### Failures")
        lines.append("")
        for t in failures:
            name = t.get("name", "unknown")
            msg = t.get("message", t.get("failure_message", ""))
            lines.append(f"- **{name}**: {msg}")
        lines.append("")


def _render_rec_metrics(
    lines: list[str], rec: dict[str, Any]
) -> None:
    """Render recommendation metrics tables."""
    if not rec:
        return
    by_k = rec.get("by_k", {})
    if not by_k:
        return

    lines.append("## Recommendation Metrics")
    lines.append("")

    # Get metric names from first entry
    first_k = next(iter(by_k.values()), {})
    metric_names = sorted(first_k.keys())

    header = "| K | " + " | ".join(metric_names) + " |"
    sep = "|---|" + "|".join(["---:" for _ in metric_names]) + "|"
    lines.append(header)
    lines.append(sep)

    for k_label in sorted(by_k.keys()):
        metrics = by_k[k_label]
        vals = " | ".join(_fmt(metrics.get(m), 6) for m in metric_names)
        lines.append(f"| {k_label} | {vals} |")
    lines.append("")

    # Latency
    lat = rec.get("latency", {})
    if lat:
        lines.append("### Latency")
        lines.append("")
        lines.append("| Percentile | Value (ms) |")
        lines.append("|------------|----------:|")
        for k, v in lat.items():
            lines.append(f"| {k} | {_fmt(v, 2)} |")
        lines.append("")


def _render_mmr(lines: list[str], mmr: dict[str, Any]) -> None:
    """Render MMR trade-off section."""
    if not mmr:
        return
    variants = mmr.get("variants", {})
    if not variants:
        return

    lines.append("## MMR Relevance–Diversity Trade-off")
    lines.append("")
    lines.append("| Variant | NDCG@10 | ILD@10 | Coverage@10 | P50 Latency (ms) |")
    lines.append("|---------|--------:|-------:|------------:|------------------:|")

    for vid, vdata in variants.items():
        name = vdata.get("name", vid)
        metrics = vdata.get("metrics", {})
        k10 = metrics.get("by_k", {}).get("k_10", {})
        lat = metrics.get("latency", {})
        lines.append(
            f"| {name} "
            f"| {_fmt(k10.get('ndcg'))} "
            f"| {_fmt(k10.get('intra_list_diversity'), 4)} "
            f"| {_fmt(k10.get('catalog_coverage'), 4)} "
            f"| {_fmt(lat.get('p50_ms'), 2)} |"
        )
    lines.append("")


def _render_latency(lines: list[str], lat_data: list[dict]) -> None:
    """Render latency comparison section."""
    if not lat_data:
        return
    lines.append("## Latency Comparison")
    lines.append("")
    lines.append("| Experiment | P50 (ms) | P90 (ms) | P95 (ms) | Mean (ms) |")
    lines.append("|------------|----------:|----------:|----------:|----------:|")
    for entry in lat_data:
        lines.append(
            f"| {entry.get('name', '—')} "
            f"| {_fmt(entry.get('p50_ms'), 2)} "
            f"| {_fmt(entry.get('p90_ms'), 2)} "
            f"| {_fmt(entry.get('p95_ms'), 2)} "
            f"| {_fmt(entry.get('mean_ms'), 2)} |"
        )
    lines.append("")


def _render_security(lines: list[str], findings: list[dict]) -> None:
    """Render security findings section."""
    if not findings:
        return
    lines.append("## Security Findings")
    lines.append("")
    lines.append("| Severity | Title | Location |")
    lines.append("|----------|-------|----------|")
    for f in findings:
        lines.append(
            f"| {f.get('severity', '—')} "
            f"| {f.get('title', '—')} "
            f"| {f.get('location', '—')} |"
        )
    lines.append("")


def _render_limitations(lines: list[str], limitations: list[str]) -> None:
    """Render known limitations section."""
    if not limitations:
        return
    lines.append("## Known Limitations")
    lines.append("")
    for lim in limitations:
        lines.append(f"- {lim}")
    lines.append("")


def _render_methodology(lines: list[str], data: dict[str, Any]) -> None:
    """Render methodology and reproducibility notes."""
    lines.append("## Reproducibility")
    lines.append("")

    meta = data.get("metadata", {})
    rec = data.get("recommendation_metrics", {})

    lines.append(f"- **Git Commit:** `{meta.get('git_commit', '—')}`")
    lines.append(f"- **Python Version:** `{meta.get('python_version', '—')}`")
    lines.append(f"- **Node Version:** `{meta.get('node_version', '—')}`")

    ds = rec.get("dataset_checksum", "")
    sp = rec.get("split_checksum", "")
    if ds:
        lines.append(f"- **Dataset SHA-256:** `{ds}`")
    if sp:
        lines.append(f"- **Split SHA-256:** `{sp}`")
    lines.append("")
